#!/usr/bin/env node
/**
 * Scans /Portfolio-images and writes js/manifest.json — a map of
 * { categoryFolderName: ["file1.jpg", "file2.jpg", ...] }.
 *
 * Run this any time you add, remove, or rename files in /Portfolio-images:
 *   node scripts/generate-manifest.js
 *
 * The site reads js/manifest.json at load time so you never have to hand-type
 * file paths — just drop images into the right folder and re-run this script.
 */
const fs = require("fs");
const path = require("path");

/**
 * Minimal, dependency-free image dimension reader (JPEG/PNG/WebP) so the
 * portfolio grid can reserve correct aspect ratio before an image finishes
 * loading — this is what makes the CSS-columns masonry layout stay stable
 * instead of collapsing to 0-height while lazy-loaded images are off-screen.
 */
function getImageSize(filePath) {
  const buf = fs.readFileSync(filePath);
  const ext = path.extname(filePath).toLowerCase();

  try {
    if (ext === ".png") {
      // PNG: width/height are big-endian uint32 at bytes 16 and 20
      if (buf.length >= 24 && buf.toString("ascii", 1, 4) === "PNG") {
        return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
      }
    } else if (ext === ".jpg" || ext === ".jpeg") {
      // JPEG: scan markers for a Start Of Frame segment
      let offset = 2; // skip SOI marker (0xFFD8)
      while (offset < buf.length) {
        if (buf[offset] !== 0xff) { offset++; continue; }
        const marker = buf[offset + 1];
        // SOF0-SOF15 except DHT(0xC4), JPG(0xC8), DAC(0xCC)
        const isSOF = marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;
        if (isSOF) {
          const height = buf.readUInt16BE(offset + 5);
          const width = buf.readUInt16BE(offset + 7);
          return { width, height };
        }
        if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
          offset += 2;
          continue;
        }
        const segLength = buf.readUInt16BE(offset + 2);
        offset += 2 + segLength;
      }
    } else if (ext === ".webp") {
      // WebP: VP8/VP8L/VP8X chunk parsing (handles the common cases)
      if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") {
        const fourcc = buf.toString("ascii", 12, 16);
        if (fourcc === "VP8X") {
          const width = 1 + (buf.readUIntLE(24, 3));
          const height = 1 + (buf.readUIntLE(27, 3));
          return { width, height };
        } else if (fourcc === "VP8 ") {
          const width = buf.readUInt16LE(26) & 0x3fff;
          const height = buf.readUInt16LE(28) & 0x3fff;
          return { width, height };
        } else if (fourcc === "VP8L") {
          const b0 = buf[21], b1 = buf[22], b2 = buf[23], b3 = buf[24];
          const width = 1 + (((b1 & 0x3f) << 8) | b0);
          const height = 1 + (((b3 & 0xf) << 10) | (b2 << 2) | ((b1 & 0xc0) >> 6));
          return { width, height };
        }
      }
    }
  } catch (e) {
    // fall through to null below
  }
  return null;
}

const IMAGES_DIR = path.join(__dirname, "..", "Portfolio-images");
// Emitted as a plain <script> global (not fetched JSON) so the site works
// even when opened directly from disk (file://), where fetch() is blocked
// by the browser's CORS rules.
const OUT_FILE = path.join(__dirname, "..", "js", "manifest.js");
const VALID_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

function main() {
  if (!fs.existsSync(IMAGES_DIR)) {
    console.error(`No Portfolio-images folder found at ${IMAGES_DIR}`);
    process.exit(1);
  }

  const manifest = {};
  const categories = fs
    .readdirSync(IMAGES_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  for (const cat of categories) {
    const dir = path.join(IMAGES_DIR, cat);
    const files = fs
      .readdirSync(dir)
      .filter((f) => VALID_EXT.has(path.extname(f).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    manifest[cat] = files.map((file) => {
      const size = getImageSize(path.join(dir, file));
      return { file, width: size ? size.width : null, height: size ? size.height : null };
    });
  }

  const banner =
    "// AUTO-GENERATED by scripts/generate-manifest.js — do not hand-edit.\n" +
    "// Re-run `node scripts/generate-manifest.js` after adding/removing images.\n";
  fs.writeFileSync(
    OUT_FILE,
    banner + "window.PORTFOLIO_MANIFEST = " + JSON.stringify(manifest, null, 2) + ";\n"
  );
  const total = Object.values(manifest).reduce((n, arr) => n + arr.length, 0);
  console.log(`Wrote ${OUT_FILE}`);
  console.log(`Found ${categories.length} categories, ${total} images:`);
  for (const cat of categories) {
    console.log(`  ${cat}: ${manifest[cat].length}`);
  }
}

main();
